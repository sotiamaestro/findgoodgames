#!/usr/bin/env sh
# One-time: publish the local .data/ output as the orphan `data` branch so the
# site has data before the first workflow run. Later runs are done by
# .github/workflows/refresh-data.yml.
set -eu
cd "$(dirname "$0")/.."
test -f .data/games.json || { echo ".data/games.json missing; run the pipeline first"; exit 1; }
tmp=$(mktemp -d)
git worktree add --detach "$tmp" >/dev/null
(
  cd "$tmp"
  git checkout -q --orphan data
  git rm -rfq . >/dev/null 2>&1 || true
  printf '# data branch\n\nGenerated by .github/workflows/refresh-data.yml and pipeline/build-data.ts. Do not edit by hand.\n' > README.md
  cp "$OLDPWD/.data/games.json" "$OLDPWD/.data/gfn-steam.json" "$OLDPWD/.data/cache.json" .
  git add -A
  git commit -q -m "data: initial snapshot $(date -u +%Y-%m-%dT%H:%MZ)"
  git push -f origin data
)
git worktree remove --force "$tmp"
echo "pushed data branch"
